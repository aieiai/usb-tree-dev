function kcDescribe(code) {
  const type = (code >>> 1) & 0x1f;
  const usage = (code >>> 24) & 0xff;
  switch (type) {
    case 0:
      return KC_USAGE_NAMES[usage] || `KBD 0x${usage.toString(16).padStart(2, '0')}`;
    case 1:
      return KC_SYS_NAMES[usage] || `SYS 0x${usage.toString(16).padStart(2, '0')}`;
    case 2: {
      const cc = (code >>> 16) & 0xffff;
      return KC_CSM_NAMES[cc] || `CSM 0x${cc.toString(16).padStart(4, '0')}`;
    }
    case 3: {
      const sy = (code >>> 6) & 0x1f;
      const co = (code >>> 24) & 0xff;
      const name = KC_ADV_NAMES[sy] || `ADV ${sy}`;
      return co !== 0 ? `${name}(${co})` : name;
    }
    case 4: {
      const sy = (code >>> 6) & 0x1f;
      if (sy === 0) {
        const co = (code >>> 16) & 0xffff;
        const names = [];
        for (let bit = 0; bit < 8; bit++) {
          if (co & (1 << bit)) names.push(KC_MS_BTN_NAMES[1 << bit]);
        }
        return names.length > 0 ? names.join('+') : `MS 按键 0x${co.toString(16)}`;
      }
      return KC_MS_NAMES[sy] || `MS 0x${sy.toString(16).padStart(2, '0')}`;
    }
    case 5: {
      const sy = (code >>> 6) & 0x1f;
      const md = (code >>> 11) & 0x07;
      const co = (code >>> 16) & 0xffff;
      const names = md === 1 ? KC_GP_XBOX_NAMES : KC_GP_CLASSIC_NAMES;
      const name = names[sy] || `GP ${sy}`;
      return `${md === 1 ? 'Xbox' : '经典'}·${name}${co !== 0 ? `(${co})` : ''}`;
    }
    case 6: {
      const sub = (code >>> 6) & 0x1f;
      const detail = (code >>> 16) & 0xffff;
      const fnNames = { 0: 'FN', 1: '灯效', 2: '蓝牙', 3: '2.4G', 4: '显示', 5: '快捷' };
      if (fnNames[sub] !== undefined) {
        const index = (sub === 0 && detail >= 0xf0) ? detail - 0xf0 : detail;
        return `${fnNames[sub]}${index}`;
      }
      return `FN${sub}:${detail.toString(16).padStart(4, '0')}`;
    }
    default:
      return `0x${(code >>> 0).toString(16).padStart(8, '0')}`;
  }
}

